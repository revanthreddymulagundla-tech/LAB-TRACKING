import { jsPDF } from 'jspdf';
import * as autoTableModule from 'jspdf-autotable';

// Works in Vite (browser) and Node (tests) regardless of CJS/ESM interop
const autoTable = autoTableModule.default?.default || autoTableModule.default || autoTableModule.autoTable;
import { examFields, formatDate, courseTitle, secsOf, venueLabel } from './searchUtils.js';

const NAVY = [17, 26, 66], VIOLET = [124, 58, 237];

function header(doc, title, subtitle) {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(...NAVY); doc.rect(0, 0, w, 24, 'F');
  doc.setFillColor(...VIOLET); doc.rect(0, 24, w, 1.6, 'F');
  doc.setTextColor(255); doc.setFont('helvetica', 'bold'); doc.setFontSize(16);
  doc.text('LABTRACK', 12, 12);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9);
  doc.text('Smart Lab Examination Schedule Portal  |  Academic Year 2026-27', 12, 18.5);
  doc.setTextColor(...NAVY); doc.setFont('helvetica', 'bold'); doc.setFontSize(13);
  doc.text(title, 12, 36);
  if (subtitle) { doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(90); doc.text(subtitle, 12, 42); }
}

function footer(doc) {
  const n = doc.getNumberOfPages(), w = doc.internal.pageSize.getWidth(), h = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= n; i++) {
    doc.setPage(i); doc.setFontSize(8); doc.setTextColor(120);
    doc.text('Generated by LabTrack from the official 2026-27 lab examination workbook. Please verify with your department.', 12, h - 8);
    doc.text(`Page ${i} of ${n}`, w - 12, h - 8, { align: 'right' });
  }
}

export function buildExamPDF(exams, title = 'Lab Examination Details') {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  header(doc, title, `${exams.length} examination record${exams.length === 1 ? '' : 's'}`);
  let y = 48;
  exams.forEach((r, i) => {
    autoTable(doc, {
      startY: y, theme: 'grid', margin: { left: 12, right: 12 },
      head: [[{ content: `${i + 1}. ${courseTitle(r)} (${r.courseCode})`, colSpan: 2 }]],
      body: examFields(r).filter(([l]) => !['Subject', 'Course Code'].includes(l)),
      headStyles: { fillColor: NAVY, textColor: 255, fontSize: 10 },
      styles: { fontSize: 9, cellPadding: 2 },
      columnStyles: { 0: { cellWidth: 45, fontStyle: 'bold', fillColor: [245, 243, 255] } }
    });
    y = doc.lastAutoTable.finalY + 8;
  });
  footer(doc);
  return doc;
}
export const downloadExamPDF = (exams, filename = 'LabTrack-Exam-Details.pdf', title) => {
  const doc = buildExamPDF(exams, title); doc.save(filename); return doc;
};

export function buildTimetablePDF(rows, title, subtitle) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'landscape' });
  header(doc, title, subtitle);
  autoTable(doc, {
    startY: 47, theme: 'striped', margin: { left: 10, right: 10 },
    head: [['Date', 'Time', 'Subject', 'Code', 'Section', 'Venue', 'Faculty']],
    body: rows.map((r) => [
      formatDate(r.date, true), r.timeDisplay || r.time || '—', courseTitle(r), r.courseCode,
      secsOf(r).length > 1 ? r.section : r.section || '—', r.venue ? `${r.venue}` : '—',
      [r.facultyA, r.facultyB].filter(Boolean).join(' / ') || '—'
    ]),
    headStyles: { fillColor: NAVY, textColor: 255 },
    alternateRowStyles: { fillColor: [245, 243, 255] },
    styles: { fontSize: 8, cellPadding: 1.8 },
    columnStyles: { 0: { cellWidth: 30 }, 1: { cellWidth: 38 }, 3: { cellWidth: 26 }, 4: { cellWidth: 18 }, 5: { cellWidth: 26 } }
  });
  footer(doc);
  return doc;
}
export const downloadTimetablePDF = (rows, title, subtitle, filename = 'LabTrack-Timetable.pdf') => {
  const doc = buildTimetablePDF(rows, title, subtitle); doc.save(filename); return doc;
};
